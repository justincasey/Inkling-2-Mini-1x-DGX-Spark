"""Writes meta.json of this record from the saved outputs in raw/: every number comes from a `test result:` line, none is typed.
A run that printed `not run` or `skipping` is not a pass of the fixture test: it is counted in metrics.still_not_run."""
import json, re, subprocess, sys
from pathlib import Path

here = Path(__file__).resolve().parent
raw = here / "raw"
# (output file, package, test binary, [filters in the order they ran], fixture variables of the run)
RUNS = [
    ("attn_oracle-real.txt", "gb-cuda", "inkling2_attn_oracle", ["real::"], "I2L_ATTN_REAL=<attn lane lab>/real/attn_real.bin"),
    ("ops-oracle.txt", "gb-cuda", "inkling2_ops", ["ops_equal_the_oracle_on_the_real_weights"], "REXL3_INKLING2_DIR=<Small pack>, REXL3_INKLING2_ORACLE=<lab>/fix/ops-small"),
    ("dspark-small-oracle.txt", "gb-cuda", "inkling2_dspark", ["matches_the_oracle_on_one_rank", "matches_the_oracle_at_tp4"], "REXL3_INKLING2_DIR=<Small pack>, REXL3_INKLING2_DSPARK_ORACLE=<node-3 Small drafter fixtures>"),
    ("dspark-mini-oracle.txt", "gb-cuda", "inkling2_dspark", ["mini_matches_the_oracle", "slim_picks_the_full_heads_winner"], "REXL3_INKLING2_LOOP_DSPARK_ORACLE=<lab>/fix/dspark-mini"),
    ("moe-mixed-bench.txt", "gb-cuda", "inkling2_moe_mixed", ["bench_decode_cost_of_bands", "bench_prefill_layers"], "REXL3_MOE_BENCH=1 (information only, no pass/fail claim)"),
]
RES = re.compile(r"test result: (?:ok|FAILED)\. (\d+) passed; (\d+) failed; (\d+) ignored;")
UNRUN = re.compile(r"not run|skipping")

tests, still = [], []
for fn, pkg, binary, filters, env in RUNS:
    text = (raw / fn).read_text(errors="replace")
    res = RES.findall(text)
    if len(res) != len(filters):
        sys.exit(f"{fn}: {len(res)} `test result:` lines for {len(filters)} filters")
    for flt, (p, f, i) in zip(filters, res):
        tests.append({"bin": f"{pkg} {binary}", "filter": flt, "passed": int(p), "failed": int(f), "ignored": int(i), "env": env})
    still += [f"{fn}: {l.strip()[:160]}" for l in text.splitlines() if UNRUN.search(l)]

engine = Path.home() / "projects/rexl3-inkling2-loop"
recipe = Path(__file__).resolve().parents[3]
git = lambda *a, c=engine: subprocess.run(["git", "-C", str(c), *a], capture_output=True, text=True, check=True).stdout.strip()
failed = sum(t["failed"] for t in tests)
meta = {
    "name": here.name.split("-", 3)[3],
    "gate": "engine-gpu-tests-fixtures",
    "date": here.name[:10],
    "result": "pass" if failed == 0 and tests and not still else "fail",
    "node": "node-3",
    "engine": {
        "commit": git("rev-parse", "HEAD"),
        "pinned_commit": "59d08a9c5e9f9d3ce96ed9d2353c68b70169cc1a",
        "dirty": bool(git("status", "--porcelain")),
        "lab_build": False,
        "version": "lab test build (cargo test --release, scripts/ops_dev.sh), no server binary",
    },
    "recipe": {"base_commit": git("rev-parse", "autoresearch/session-20261122", c=recipe)},
    "tests": tests,
    "metrics": {
        "tests_passed": sum(t["passed"] for t in tests),
        "tests_failed": failed,
        "still_not_run": len(still),
    },
    "still_not_run": still,
    "notes": "The tests that printed `not run` in 2026-11-24-engine-gpu-tests-pin, run with their real fixtures at the pinned engine commit on node-3 under the 2,200 MHz cap; generated by derive_meta.py from raw/*.txt. The two moe_mixed benchmarks print timings as information only.",
}
(here / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")
print(json.dumps(meta["metrics"]), meta["result"])
