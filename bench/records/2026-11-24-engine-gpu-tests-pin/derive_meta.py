"""Writes meta.json of this record from the saved outputs in raw/: every number comes from a `test result:` line, none is typed."""
import json, re, subprocess, sys
from pathlib import Path

here = Path(__file__).resolve().parent
raw = here / "raw"
# (output file, package, test binary, environment of the run)
RUNS = [
    ("gb-cuda-inkling2_attn.txt", "gb-cuda", "inkling2_attn", ""),
    ("gb-cuda-inkling2_attn_oracle.txt", "gb-cuda", "inkling2_attn_oracle", ""),
    ("gb-cuda-inkling2_ops.txt", "gb-cuda", "inkling2_ops", "REXL3_INKLING2_DIR=<Small pack>"),
    ("gb-cuda-inkling2_dspark.txt", "gb-cuda", "inkling2_dspark", "REXL3_INKLING2_DIR=<Small pack>"),
    ("gb-cuda-inkling2_moe.txt", "gb-cuda", "inkling2_moe", "REXL3_INKLING2_DIR=<Small pack>, REXL3_INKLING2_RANK=2 (node-3 holds rank 2's share)"),
    ("gb-cuda-inkling2_moe_mixed.txt", "gb-cuda", "inkling2_moe_mixed", "REXL3_INKLING2_DIR=<Small pack>"),
    ("gb-cuda-inkling2_loop_vision.txt", "gb-cuda", "inkling2_loop_vision", "REXL3_INKLING2_DIR=<Small pack>"),
    ("gb-model-inkling2_vision.txt", "gb-model", "inkling2_vision", "REXL3_INKLING2_DIR=<Small pack>"),
    ("gb-model-inkling2_loop_vision.txt", "gb-model", "inkling2_loop_vision", "REXL3_INKLING2_DIR=<Small pack>"),
]
RES = re.compile(r"test result: (?:ok|FAILED)\. (\d+) passed; (\d+) failed; (\d+) ignored;")
NOT_RUN = re.compile(r"^test (\S+) \.\.\. .*not run", re.M)
SKIP = re.compile(r"^test (\S+) \.\.\. .*skipping", re.M)

tests, table = [], []
for fn, pkg, binary, env in RUNS:
    text = (raw / fn).read_text(errors="replace")
    m = RES.findall(text)
    if len(m) != 1:
        sys.exit(f"{fn}: {len(m)} `test result:` lines, expected 1")
    p, f, i = map(int, m[0])
    t = {"bin": f"{pkg} {binary}", "filter": "(all)", "passed": p, "failed": f, "ignored": i}
    if env:
        t["env"] = env
    nr = sorted(NOT_RUN.findall(text) + SKIP.findall(text))
    if nr:
        t["not_run"] = nr
    tests.append(t)

engine = Path.home() / "projects/rexl3-inkling2-loop"
git = lambda *a, c=engine: subprocess.run(["git", "-C", str(c), *a], capture_output=True, text=True, check=True).stdout.strip()
recipe = Path(__file__).resolve().parents[3]
failed = sum(t["failed"] for t in tests)
meta = {
    "name": here.name.split("-", 3)[3],
    "gate": "engine-gpu-tests",
    "date": here.name[:10],
    "result": "pass" if failed == 0 and tests else "fail",
    "node": "node-3",
    "engine": {
        "commit": git("rev-parse", "HEAD"),
        "pinned_commit": "59d08a9c5e9f9d3ce96ed9d2353c68b70169cc1a",
        "dirty": bool(git("status", "--porcelain")),
        "lab_build": False,
        "version": "lab test build (cargo test --release, scripts/ops_dev.sh), no server binary",
    },
    "recipe": {"base_commit": git("rev-parse", "autoresearch/session-20261122", c=recipe)},
    "tests": tests,
    "metrics": {
        "binaries": len(tests),
        "tests_passed": sum(t["passed"] for t in tests),
        "tests_failed": failed,
        "tests_ignored": sum(t["ignored"] for t in tests),
        "tests_not_run_printed": sum(len(t.get("not_run", [])) for t in tests),
    },
    "notes": "Every GPU test binary of the Mini family run whole (empty filter) at the pinned engine commit on node-3 under the 2,200 MHz cap; generated by derive_meta.py from raw/*.txt.",
}
(here / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")
print(json.dumps(meta["metrics"]), meta["result"])
for t in tests:
    print(t["bin"], t["passed"], t["failed"], t["ignored"], len(t.get("not_run", [])))
